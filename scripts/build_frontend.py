"""Build the single workbench stylesheet and its generated color themes.

Run: python -m scripts.build_frontend [--check]
Edit the module files named in workbench.sources.json, never generated files.
"""
import argparse
import json
from pathlib import Path

from scripts.build_ui_themes import main as build_themes

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / 'app/static/css'
HEADER = '/* Generated by python -m scripts.build_frontend. Edit workbench.sources.json module sources. */\n'


def workbench_content(css_dir: Path = CSS) -> str:
    sources = json.loads((css_dir / 'workbench.sources.json').read_text(encoding='utf-8'))['sources']
    if len(sources) != len(set(sources)):
        raise ValueError('Duplicate stylesheet in workbench.sources.json')
    sections = [HEADER]
    for name in sources:
        path = (css_dir / name).resolve()
        if path.parent != css_dir.resolve() or path.suffix != '.css' or name in {'workbench.css', 'ui-themes.css'}:
            raise ValueError('Invalid stylesheet source: ' + name)
        sections.append(f'/* Module: {name} */\n' + path.read_text(encoding='utf-8').strip() + '\n')
    return '\n'.join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check that workbench.css matches module sources without writing files')
    args = parser.parse_args()
    target = CSS / 'workbench.css'
    content = workbench_content()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            parser.exit(1, 'Styles are out of date. Run python -m scripts.build_frontend.\n')
        print('Workbench stylesheet is up to date.')
        return
    target.write_text(content, encoding='utf-8')
    print(f'Built workbench.css: {target.stat().st_size} bytes')
    build_themes()


if __name__ == '__main__':
    main()
